import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Reviewed @hey-api/openapi-ts 0.99.0 output, normalized to LF. An upstream
// change requires re-reviewing the complete helper, not silently skipping a fix.
const upstreamSHA256 =
  "097c75f6e269c6c8680641091832a69b38e8828e8ee8465318d32a177593330f";
const originalWriteSlot = `  function writeSlot(slot: Slot, key: string, value: unknown): void {
    let record = params[slot] as Record<string, unknown> | undefined;
    if (record === undefined) {
      record = Object.create(null) as Record<string, unknown>;
      params[slot] = record;
    }
    record[key] = value;
  }`;
const hardenedWriteSlot = `  // Periapsis: generated by scripts/harden-generated-params.mjs.
  const ownedRecords = new WeakSet<object>([params.headers, params.path, params.query]);

  function assertSlot(slot: unknown): asserts slot is Slot {
    if (slot !== 'body' && slot !== 'headers' && slot !== 'path' && slot !== 'query') {
      throw new TypeError('Invalid client parameter slot');
    }
  }

  function writeSlot(slot: Slot, key: string, value: unknown): void {
    assertSlot(slot);
    if (typeof key !== 'string' || key === '__proto__' || key === 'constructor' || key === 'prototype') {
      throw new TypeError('Invalid client parameter key');
    }
    let record = params[slot] as Record<string, unknown> | undefined;
    if (record === undefined) {
      record = Object.create(null) as Record<string, unknown>;
    } else if (!ownedRecords.has(record)) {
      if (record === null || typeof record !== 'object' || Array.isArray(record) ||
          (Object.getPrototypeOf(record) !== null && Object.getPrototypeOf(record) !== Object.prototype)) {
        throw new TypeError('Client parameter field writes require a plain record');
      }
      record = Object.assign(Object.create(null), record) as Record<string, unknown>;
    }
    ownedRecords.add(record);
    params[slot] = record;
    record[key] = value;
  }`;

export function hardenGeneratedParams(source) {
  const normalized = source.replaceAll("\r\n", "\n");
  if (
    createHash("sha256").update(normalized).digest("hex") !== upstreamSHA256
  ) {
    throw new Error(
      "generated params template changed; security review required",
    );
  }
  return normalized
    .replace(originalWriteSlot, hardenedWriteSlot)
    .replace(
      "            params[field.map] = value;",
      "            assertSlot(field.map);\n            params[field.map] = value;",
    );
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const target = new URL(
    "../generated/typescript/core/params.gen.ts",
    import.meta.url,
  );
  const hardened = hardenGeneratedParams(readFileSync(target, "utf8"));
  writeFileSync(target, hardened, "utf8");
}
