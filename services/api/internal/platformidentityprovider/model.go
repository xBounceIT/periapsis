// EncryptedOIDCClientSecret is the only secret-bearing representation allowed
// across the repository port.
type EncryptedOIDCClientSecret struct {
	SecretID uuid.UUID
	Envelope identity.OIDCClientSecretEnvelope
}

func (secret EncryptedOIDCClientSecret) String() string {
	return fmt.Sprintf(
		"platformidentityprovider.EncryptedOIDCClientSecret{key_version:%d,ciphertext_bytes:%d,material:[REDACTED]}",
		secret.Envelope.KeyVersion, len(secret.Envelope.Ciphertext),
	)
}

func (secret EncryptedOIDCClientSecret) GoString() string { return secret.String() }
