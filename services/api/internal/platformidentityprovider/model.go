// DirectLoginInput is the reason-bearing, exact-version command shared by
// the explicit direct platform OIDC login lifecycle actions. The direct
// account mode is deliberately absent: v1 always admits pre-linked existing
// identities and provider claims never create platform authority.
type DirectLoginInput struct {
	Reason            string
	ExpectedEntityTag *string
	Event             authentication.EventContext
}

