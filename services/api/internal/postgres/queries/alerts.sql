-- name: GetAlert :one
SELECT
  id,
  tenant_id,
  external_id,
  title,
  description,
  status,
  severity,
  created_by,
  created_at,
  updated_at,
  version
FROM alerts
WHERE tenant_id = sqlc.arg(tenant_id)::uuid
  AND id = sqlc.arg(id)::uuid
  AND deleted_at IS NULL;

-- name: ListAlerts :many
SELECT
  id,
  tenant_id,
  external_id,
  title,
  description,
  status,
  severity,
  created_by,
  created_at,
  updated_at,
  version
FROM alerts
WHERE tenant_id = sqlc.arg(tenant_id)::uuid
  AND deleted_at IS NULL
  AND (
    sqlc.narg(after_id)::uuid IS NULL
    OR id > sqlc.narg(after_id)::uuid
  )
ORDER BY id ASC
LIMIT sqlc.arg(page_size);

